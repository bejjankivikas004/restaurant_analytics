SELECT
    COUNT(*) AS TOTAL_FACT_ROWS,
    COUNT_IF(c.CUSTOMER_ID IS NULL) AS INVALID_CUSTOMERS,
    COUNT_IF(m.MENU_ITEM_ID IS NULL) AS INVALID_MENU_ITEMS,
    COUNT_IF(r.RESTAURANT_ID IS NULL) AS INVALID_RESTAURANTS,
    COUNT_IF(d.DATE IS NULL) AS INVALID_DATES
FROM RESTAURANT_DB.GOLD.FACT_ORDERS f
LEFT JOIN RESTAURANT_DB.GOLD.DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
LEFT JOIN RESTAURANT_DB.GOLD.DIM_MENU_ITEM m
    ON f.MENU_ITEM_ID = m.MENU_ITEM_ID
LEFT JOIN RESTAURANT_DB.GOLD.DIM_RESTAURANT r
    ON f.RESTAURANT_ID = r.RESTAURANT_ID
LEFT JOIN RESTAURANT_DB.GOLD.DIM_DATE d
    ON f.ORDER_DATE = d.DATE;


