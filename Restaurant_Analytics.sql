SELECT
    PIPE_NAME,
    IS_AUTOINGEST_ENABLED,
    NOTIFICATION_CHANNEL_NAME
FROM RESTAURANT_DB.INFORMATION_SCHEMA.PIPES
WHERE PIPE_SCHEMA = 'BRONZE'
  AND PIPE_NAME IN (
      'PIPE_CUSTOMERS',
      'PIPE_ORDERS',
      'PIPE_MENU_ITEMS',
      'PIPE_LOCATIONS',
      'PIPE_DELIVERY',
      'PIPE_REVIEWS'
  )
ORDER BY PIPE_NAME;


SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT ORDER_ID) AS UNIQUE_ORDERS,
    COUNT_IF(ORDER_ID IS NULL) AS NULL_ORDER_IDS,
    COUNT_IF(ORDER_DATE IS NULL) AS NULL_ORDER_DATES
FROM RESTAURANT_DB.BRONZE.BRONZE_ORDERS;
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT CUSTOMER_ID) AS UNIQUE_CUSTOMERS,
    COUNT_IF(CUSTOMER_ID IS NULL) AS NULL_CUSTOMER_IDS,
    COUNT_IF(EMAIL IS NULL) AS NULL_EMAILS
FROM RESTAURANT_DB.BRONZE.BRONZE_CUSTOMERS;
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT REVIEW_ID) AS UNIQUE_REVIEWS,
    COUNT_IF(REVIEW_ID IS NULL) AS NULL_REVIEW_IDS,
    COUNT_IF(CUSTOMER_ID IS NULL) AS NULL_CUSTOMER_IDS,
    COUNT_IF(RATING IS NULL) AS NULL_RATINGS
FROM RESTAURANT_DB.BRONZE.BRONZE_REVIEWS;
SELECT
    COUNT(*) AS TOTAL_ROWS,
    COUNT(DISTINCT MENU_ITEM_ID) AS UNIQUE_MENU_ITEMS,
    COUNT_IF(MENU_ITEM_ID IS NULL) AS NULL_MENU_ITEM_IDS,
    COUNT_IF(ITEM_NAME IS NULL) AS NULL_ITEM_NAMES,
    COUNT_IF(LIST_PRICE IS NULL) AS NULL_LIST_PRICES
FROM RESTAURANT_DB.BRONZE.BRONZE_MENU_ITEMS;


